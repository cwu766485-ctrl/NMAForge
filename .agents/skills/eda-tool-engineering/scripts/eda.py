"""Small, dependency-free project EDA API/CLI."""
import argparse, datetime as dt, json, os, re, shutil, subprocess, sys
from pathlib import Path

HOME_DEFAULTS = {
    "vcs": ("VCS_HOME", "vcs"), "verdi": ("VERDI_HOME", "verdi"),
    "spyglass": ("SPYGLASS_HOME", "sg_shell"), "formal": ("FM_HOME", "fm_shell"),
    "vcf": ("VC_FORMAL_HOME", "vc_static_shell"), "dc": ("DC_HOME", "dc_shell"),
    "icc2": ("ICC2_HOME", "icc2_shell"), "icc": ("ICC_HOME", "icc_shell"),
    "pt": ("PRIME_HOME", "pt_shell"), "starrc": ("STARRC_HOME", "starrc_shell"),
    "dft": ("TESTMAX_HOME", "dft_shell"), "tmax": ("TESTMAX_HOME", "tmax"),
    "rtla": ("RTLA_HOME", "rtl_shell"), "lc": ("LC_HOME", "lc_shell"),
}
FLOW_TOOL = {"sim":"vcs", "debug":"verdi", "lint":"spyglass", "cdc":"spyglass",
             "formal":"vcf", "formality":"formal", "synth":"dc", "dft":"dc", "atpg":"tmax",
             "mbist":"dft", "lbist":"dft", "apr":"icc2", "sta":"pt",
             "power":"pt", "starrc":"starrc"}

def project_root():
    return Path.cwd()

def parse_config(path):
    """Parse the intentionally small contract without requiring PyYAML."""
    if not path.exists(): return {}
    data = {}
    for line in path.read_text(errors="replace").splitlines():
        line = line.split("#", 1)[0].rstrip()
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m and not m.group(2).startswith(("-", "{", "[")):
            val = m.group(2).strip().strip("'\"")
            data[m.group(1)] = val
    return data

def parse_dft_reports(root):
    reports = root / "reports"
    result = {"project_root": str(root), "reports_dir": str(reports), "status": "unknown", "checks": {}}
    for name in ("dft_pre.rpt", "dft_post.rpt"):
        p = reports / name
        if not p.exists(): continue
        text = p.read_text(errors="replace")
        m = re.search(r"Total violations:\s*(\d+)", text)
        cells = re.search(r"\*\s+(\d+) cells are valid scan cells", text)
        result["checks"][name] = {"total_violations": int(m.group(1)) if m else None,
                                   "valid_scan_cells": int(cells.group(1)) if cells else None}
    p = reports / "scan_chain.rpt"
    if p.exists():
        text = p.read_text(errors="replace")
        rows = re.findall(r"^I\s+(\d+)\s+(\d+)\s+\S+\s+\S+\s+\S+", text, re.M)
        result["scan_chains"] = [{"chain": int(a), "length": int(b)} for a,b in rows]
    p = reports / "dft_qor.rpt"
    if p.exists():
        text = p.read_text(errors="replace")
        def num(label):
            m = re.search(re.escape(label) + r":\s*([-+]?\d+(?:\.\d+)?)", text)
            return float(m.group(1)) if m else None
        result["qor"] = {"cell_area": num("Cell Area"), "wns": num("Design  WNS"), "tns": num("Design  WNS")}
    violations = [v["total_violations"] for v in result["checks"].values() if v.get("total_violations") is not None]
    if violations and all(v == 0 for v in violations): result["status"] = "pass"
    elif violations: result["status"] = "fail"
    return result

def discover_top(root, configured=None):
    if configured and not configured.lower().startswith(("tb_", "test_", "testbench")):
        return configured
    modules = []
    for src in rtl_sources(root):
        try: modules += re.findall(r"\bmodule\s+([A-Za-z_][\w$]*)", Path(src).read_text(errors="replace"))
        except OSError: pass
    non_tb = [m for m in modules if not m.lower().startswith(("tb_", "test_", "testbench"))]
    return (non_tb or modules or [root.name])[0]

def latest_artifact(root, names):
    candidates = []
    for base in (root / "runs", root):
        for name in names: candidates += [p for p in base.glob("**/" + name) if p.is_file()]
    return str(max(candidates, key=lambda p: p.stat().st_mtime)) if candidates else None

def executable(tool):
    env_name, name = HOME_DEFAULTS[tool]
    home = os.environ.get(env_name)
    candidate = Path(home) / "bin" / name if home else None
    return str(candidate) if candidate and candidate.exists() else shutil.which(name)

def ensure_config(root):
    path = root / "eda.yaml"
    if not path.exists():
        print(f"[eda] no eda.yaml found; initializing {path}", file=sys.stderr)
        init_config(root)
    return path

def rtl_sources(root):
    out = []
    for pat in ("rtl/**/*.sv", "rtl/**/*.v", "src/**/*.sv", "src/**/*.v"):
        out += sorted(str(p) for p in root.glob(pat) if p.is_file())
    return list(dict.fromkeys(out))

def tcl_header(flow):
    return f"# Generated by eda-tool-engineering ({flow}); edit eda.yaml, not this file.\n"

def yaml_scalar(path, key, default=None):
    """Read simple scalar/nested values from the dependency-free contract parser."""
    if not path.exists(): return default
    lines = path.read_text(errors="replace").splitlines()
    for i, raw in enumerate(lines):
        line = raw.split("#", 1)[0].rstrip()
        m = re.match(r"^(\s*)" + re.escape(key) + r":\s*(.*?)\s*$", line)
        if not m: continue
        value = m.group(2).strip().strip("'\"")
        if value: return value
        # A nested mapping's first scalar is not a value for this key.
    return default

def dft_paths(root, cfg):
    cfg_path = root / "eda.yaml"
    netlist = yaml_scalar(cfg_path, "scan_netlist") or "netlist/tsmc28_smoke_scan.v"
    spf = yaml_scalar(cfg_path, "test_protocol") or "dft/tsmc28_smoke.spf"
    library = yaml_scalar(cfg_path, "library_verilog")
    if not library:
        hits = list(root.glob("**/*_Front_End*/verilog/*.v")) + list(root.glob("**/digital/**/*.v"))
        library = str(hits[0]) if hits else ""
    return netlist, spf, library

def write_atpg_script(path, top, netlist, spf, library, model):
    delay = "\nset_delay -launch system" if model == "transition" else ""
    libline = f"read_netlist -library {{{library}}}" if library else "# TODO: set library_verilog in eda.yaml"
    path.write_text("\n".join([
        f"# Generated TestMAX ATPG script ({model})", "set_commands noabort",
        f"set_messages -log ./logs/{model}_internal.log -replace", libline,
        f"read_netlist {{{netlist}}}", f"run_build_model {top}",
        f"set_drc {{{spf}}}", "run_drc", "report_rules -fail",
        f"set_faults -model {('stuck' if model == 'stuck_at' else model)}", delay,
        "add_faults -all", "run_atpg -auto", "report_faults -summary",
        f"write_patterns ./patterns/{top}_{model}.stil -format STIL -replace",
        "exit -force", ""
    ]))

def atpg_metrics(root):
    metrics = {}
    for p in list((root / "atpg").glob("**/*")) + list((root / "runs").glob("**/*")):
        if not p.is_file() or p.suffix not in (".rpt", ".log"): continue
        text = p.read_text(errors="replace")
        for label, key in (("Detected Faults", "detected_faults"), ("Undetected Faults", "undetected_faults"), ("Aborted Faults", "aborted_faults"), ("Total Patterns", "patterns")):
            m = re.search(re.escape(label) + r"\s*[:=]?\s*(\d+)", text, re.I)
            if m: metrics[key] = int(m.group(1))
        m = re.search(r"(?:fault|test)\s+coverage\s*[:=]?\s*([0-9]+(?:\.\d+)?)\s*%", text, re.I)
        if m: metrics["coverage_percent"] = float(m.group(1))
    return metrics

def generate_dft_manager(root, cfg, run_dir, flow):
    top = discover_top(root, cfg.get("top")); netlist, spf, library = dft_paths(root, cfg)
    if flow == "atpg":
        netlist = yaml_scalar(root / "eda.yaml", "scan_netlist") or latest_artifact(root, ["dft_netlist.v", "*_scan.v"]) or netlist
        spf = yaml_scalar(root / "eda.yaml", "test_protocol") or latest_artifact(root, ["design.spf", "*.spf"]) or spf
    rtl = rtl_sources(root)
    # Scan insertion is a DC DFT flow; TestMAX tmax consumes its SPF/netlist for ATPG.
    scan = run_dir / "scan_insert.tcl"
    rtl_list = " ".join("{" + x + "}" for x in rtl)
    scan.write_text("\n".join([
        tcl_header("dft-scan"), f"set TOP {top}", f"set RUN {{{run_dir}}}",
        f"set TARGET_DB {{{os.environ.get('TSMC28_STD_TT', '')}}}",
        "if {$TARGET_DB ne \"\"} { set_app_var target_library [list $TARGET_DB]; set_app_var link_library [list \"*\" $TARGET_DB] }",
        f"read_verilog -rtl [list {rtl_list}]", "current_design $TOP", "link", "compile -scan",
        "# Configure these ports/clocks in eda.yaml before execution.",
        "set_dft_signal -view existing_dft -type ScanClock -port clk -timing {45 55}",
        "set_dft_signal -view existing_dft -type Reset -port rst_n -active_state 0",
        "set_dft_signal -view spec -type ScanDataIn -port scan_in",
        "set_dft_signal -view spec -type ScanDataOut -port scan_out",
        "set_dft_signal -view spec -type ScanEnable -port scan_en -active_state 1",
        "set_scan_configuration -style multiplexed_flip_flop -chain_count 1",
        "create_test_protocol", "dft_drc -verbose > $RUN/dft_pre.rpt", "preview_dft -show all > $RUN/preview_dft.rpt",
        "insert_dft", "dft_drc -verbose > $RUN/dft_post.rpt",
        "report_scan_path -view existing_dft -chain all > $RUN/scan_chain.rpt",
        "report_scan_path -view existing_dft -cell all > $RUN/scan_cells.rpt",
        "report_dft_signal -view existing_dft -port * > $RUN/dft_signals.rpt",
        f"write -format verilog -hierarchy -output {{{run_dir}/dft_netlist.v}}",
        f"write_test_protocol -output {{{run_dir}/design.spf}}", "exit", ""
    ]))
    artifacts = [str(scan)]
    if flow in ("dft", "atpg"):
        for model in ("stuck_at", "transition"):
            p = run_dir / f"atpg_{model}.cmd"; write_atpg_script(p, top, netlist, spf, library, model); artifacts.append(str(p))
    if flow in ("dft", "mbist"):
        p = run_dir / "mbist.tcl"; p.write_text("\n".join(["# TestMAX MBIST integration template", f"# read_netlist {{{netlist}}}", "# load_library dft_mbist.sldb", "# configure_memory_bist -controller <licensed_controller>", "# insert_memory_bist", "# write_netlist ./mbist_netlist.v", ""])); artifacts.append(str(p))
    if flow in ("dft", "lbist"):
        p = run_dir / "lbist.tcl"; p.write_text("\n".join(["# TestMAX LBIST integration template", f"# read_netlist {{{netlist}}}", "# load_library dft_lbist.sldb", "# configure_logic_bist -controller <licensed_controller>", "# insert_logic_bist", "# write_netlist ./lbist_netlist.v", ""])); artifacts.append(str(p))
    command_tool = "dc" if flow == "dft" else ("tmax" if flow == "atpg" else "dft")
    command_script = scan if flow == "dft" else (run_dir / "atpg_stuck_at.cmd" if flow == "atpg" else run_dir / f"{flow}.tcl")
    command = [executable(command_tool) or HOME_DEFAULTS[command_tool][1], "-f", str(command_script)]
    return command, command_script, artifacts

def adapter(flow, root, cfg, run_dir):
    top = discover_top(root, cfg.get("top"))
    sources = rtl_sources(root)
    fl = run_dir / "rtl.f"
    fl.write_text("\n".join(sources) + ("\n" if sources else ""))
    if flow in ("dft", "atpg", "mbist", "lbist"):
        command, script, artifacts = generate_dft_manager(root, cfg, run_dir, flow)
        return command, script
    if flow == "sim":
        tb = cfg.get("sim_tb", "sim/tb_top.sv")
        cmd = [executable("vcs") or "vcs", "-full64", "-sverilog", "-f", str(fl), tb, "-top", top, "-o", str(run_dir/"simv")]
        return cmd, None
    if flow == "debug":
        return [executable("verdi") or "verdi", "-sv", "-f", str(fl), "-top", top], None
    tcl_tool = {"synth":"dc", "lint":"spyglass", "cdc":"spyglass", "dft":"dft",
                "atpg":"tmax", "mbist":"dft", "lbist":"dft", "formal":"vcf",
                "formality":"formal"}.get(flow)
    if flow == "formal": tcl_tool = "vcf"
    if flow == "formality": tcl_tool = "formal"
    if not tcl_tool: tcl_tool = FLOW_TOOL.get(flow, "dc")
    script = run_dir / f"{flow}.tcl"
    lines = [tcl_header(flow), f"set TOP {top}", f"set ROOT {{{root}}}", f"set RUN {{{run_dir}}}"]
    lines += [f"set RTL_FILES [list {' '.join('{' + x + '}' for x in sources)}]"]
    if flow == "synth":
        lines += ["set_app_var search_path [list $ROOT $ROOT/rtl]", "read_verilog -rtl $RTL_FILES", "current_design $TOP", "link", "check_design", "compile_ultra", "write -format verilog -hierarchy -output $RUN/netlist.v", "write_sdc $RUN/constraints.sdc", "report_qor > $RUN/qor.rpt", "report_timing -max_paths 20 > $RUN/timing.rpt", "report_area > $RUN/area.rpt"]
        cmd = [executable("dc") or "dc_shell", "-f", str(script)]
    elif flow in ("lint", "cdc"):
        lines += ["new_project -name eda_run -dir $RUN", "read_file -type verilog $RTL_FILES", "current_goal lint/lint_rtl", "run_goal"]
        cmd = [executable("spyglass") or "sg_shell", "-tcl", str(script)]
    elif flow == "formal":
        lines += ["read_verilog -r $RTL_FILES", "set_top $TOP", "check_fv_setup", "match", "verify", "report_fv -summary"]
        cmd = [executable("vcf") or "vc_static_shell", "-f", str(script)]
    elif flow == "formality":
        lines += ["read_verilog -golden $RTL_FILES", "read_verilog -revised $RTL_FILES", "set_top r:/WORK/$TOP", "match", "verify", "report_verification"]
        cmd = [executable("formal") or "fm_shell", "-f", str(script)]
    else:
        lines += ["puts {Adapter placeholder: provide project-specific Tcl in eda.yaml flows.*.script}"]
        cmd = [executable(tcl_tool) or tcl_tool, "-f", str(script)]
    script.write_text("\n".join(lines) + "\n")
    return cmd, script

def init_config(root, name=None, top=None, force=False):
    path = root / "eda.yaml"
    if path.exists() and not force:
        print(f"exists: {path} (use --force only if you intend to replace it)")
        return 2
    name = name or root.name
    top = top or name
    for src in list(root.glob("**/*.sv")) + list(root.glob("**/*.v")):
        try:
            m = re.search(r"\bmodule\s+([A-Za-z_][\w$]*)", src.read_text(errors="replace"))
            if m:
                top = m.group(1); break
        except OSError:
            pass
    path.write_text("\n".join([
        f"name: {name}", f"top: {top}", "rtl:", "  - rtl/**/*.sv", "  - rtl/**/*.v",
        "filelists: []", "include_dirs: []", "defines: []", "pdk:",
        "  root: /path/to/pdk/TSMC28", "  target_library: path/to/slow.db",
        f"constraints: constraints/{name}.sdc", "flows:",
        "  sim: {simulator: vcs, tb: sim/tb_top.sv}",
        "  synth: {tool: dc, script: scripts/run_dc.tcl}",
        "  apr: {tool: icc2, script: scripts/run_icc2.tcl}",
        "  sta: {tool: pt, script: scripts/run_pt.tcl}", "dft:",
        "  enabled: false", "  scan: {chains: 1, compression: false}",
        "  mbist: {enabled: false, controller: vendor_ip}",
        "  lbist: {enabled: false, controller: vendor_ip}",
        "  atpg: {faults: [stuck_at, transition], tool: tmax}", ""
    ]))
    print(f"created: {path}")
    return 0

def main():
    ap = argparse.ArgumentParser(prog="eda.py")
    ap.add_argument("command", choices=["init", "doctor", "plan", "run", "report", "validate"])
    ap.add_argument("--flow", choices=sorted(FLOW_TOOL))
    ap.add_argument("--tool", choices=sorted(HOME_DEFAULTS))
    ap.add_argument("--name")
    ap.add_argument("--top")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--execute", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    root = project_root()
    if args.command == "init":
        return init_config(root, args.name, args.top, args.force)
    config_path = ensure_config(root)
    cfg = parse_config(config_path)
    if args.command in ("report", "validate"):
        report = parse_dft_reports(root)
        report["atpg"] = atpg_metrics(root)
        print(json.dumps(report, indent=2))
        return 0 if args.command == "report" or report["status"] in ("pass", "unknown") else 1
    if args.command == "doctor":
        print(json.dumps({"project_root": str(root), "config": str(root/"eda.yaml"),
                          "config_present": (root/"eda.yaml").exists(),
                          "top": cfg.get("top"),
                          "tools": {k: executable(k) for k in HOME_DEFAULTS}}, indent=2))
        return 0
    if not args.flow: ap.error("--flow is required for plan/run")
    tool = args.tool or FLOW_TOOL[args.flow]; exe = executable(tool)
    run_id = dt.datetime.now().strftime("%Y%m%d-%H%M%S") + "-" + args.flow
    run_dir = root / "runs" / run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    command, script = adapter(args.flow, root, cfg, run_dir)
    manifest = {"flow": args.flow, "tool": tool, "executable": exe,
                "project_root": str(root), "config": str(root/"eda.yaml"),
                "command": command, "generated_script": str(script) if script else None,
                "environment": {k:v for k,v in os.environ.items() if k.endswith("_HOME") or k.endswith("_LICENSE_FILE")}}
    print(json.dumps(manifest, indent=2))
    if args.command == "plan" or not args.execute or args.dry_run: return 0
    (run_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    with (run_dir / "tool.log").open("w") as log:
        return subprocess.call(command, cwd=root, stdout=log, stderr=subprocess.STDOUT)

if __name__ == "__main__": sys.exit(main())
