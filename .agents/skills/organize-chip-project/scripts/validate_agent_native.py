#!/usr/bin/env python3
"""Validate the minimum evidence surfaces of an Agent-Native project overlay."""

from __future__ import print_function

import argparse
import json
from pathlib import Path


REQUIRED_DOCS = (
    "docs/ai-native/repository-map.md",
    "docs/ai-native/design-verification-index.md",
    "docs/ai-native/commands.md",
    "docs/ai-native/inventory.json",
    "docs/exec-plans/active/execution-frontier.md",
)
TOPIC_GROUPS = {
    "purpose/status": ("purpose", "scope", "current state"),
    "sources of truth": ("source of truth", "sources of truth"),
    "important paths": ("important paths", "path"),
    "commands": ("command", "setup", "tool entry"),
    "boundaries": ("modification", "generated", "vendor", "protected"),
    "next action": ("frontier", "next action", "definition of done"),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    agents = root / "AGENTS.md"
    missing = []
    warnings = []
    if not agents.is_file():
        missing.append("AGENTS.md")
        text = ""
        lines = []
    else:
        text = agents.read_text(encoding="utf-8", errors="replace")
        lines = text.splitlines()
        if len(lines) > 150:
            missing.append("AGENTS.md exceeds 150 lines (%d)" % len(lines))
        if "TODO" in text:
            missing.append("AGENTS.md contains TODO")
        lower = text.lower()
        for topic, cues in TOPIC_GROUPS.items():
            if not any(cue in lower for cue in cues):
                warnings.append("AGENTS.md has no obvious %s section" % topic)
    for relative in REQUIRED_DOCS:
        if not (root / relative).is_file():
            missing.append(relative)
    inventory = root / "docs/ai-native/inventory.json"
    if inventory.is_file():
        try:
            data = json.loads(inventory.read_text(encoding="utf-8"))
            if data.get("generator") != "organize-chip-project":
                warnings.append("inventory was not marked as generated by organize-chip-project")
        except ValueError:
            missing.append("docs/ai-native/inventory.json is not valid JSON")
    report = {
        "root": str(root),
        "agents_line_count": len(lines),
        "missing_or_invalid": missing,
        "warnings": warnings,
        "agent_native_minimum_ok": not missing,
    }
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0 if not missing else 2


if __name__ == "__main__":
    raise SystemExit(main())
